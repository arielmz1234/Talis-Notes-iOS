"""Writes App/Sources/Theme/Palettes.swift from the Android app's theme/Palettes.kt (the Sky, Sage
and Peach colour families). Run again if the Android palettes change.

    python tools/import_palettes.py C:/dev/Talis-Notes/app/src/main/java/com/tali/notes/theme/Palettes.kt
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1] if len(sys.argv) > 1 else "C:/dev/Talis-Notes/app/src/main/java/com/tali/notes/theme/Palettes.kt").read_text(encoding="utf-8")
blocks = re.findall(r"internal val (\w+) =\s*\n\s*(\w+)\(\s*\n(.*?)\n\s*\)\n", src, re.S)


def value(v):
    v = v.strip().rstrip(",")
    m = re.match(r"Color\(0x([0-9A-Fa-f]{8})\)", v)
    if m:
        return f"Color(argb: 0x{m.group(1)})"
    m = re.match(r"0x([0-9A-Fa-f]{8})(\.toInt\(\))?$", v)
    if m:
        return f"Color(argb: 0x{m.group(1)})"
    if v in ("true", "false"):
        return v
    raise ValueError(v)


out = ["// Generated by tools/import_palettes.py from the Android app's theme/Palettes.kt. Don't edit by hand.", "import SwiftUI", "", "extension TaliColors {"]
for name, ctor, body in blocks:
    fields = re.findall(r"(\w+) = ([^,\n]+),?", body)
    swift = name[0].lower() + name[1:]
    if ctor == "TaliColors":
        args = ", ".join(f"{k}: {value(v)}" for k, v in fields)
        out.append(f"  static let {swift} = TaliColors({args})")
    else:
        base = ctor.split(".")[0]
        base = base[0].lower() + base[1:]
        lines = [f"  static let {swift}: TaliColors = {{", f"    var m = TaliColors.{base}"]
        lines += [f"    m.{k} = {value(v)}" for k, v in fields]
        lines += ["    return m", "  }()"]
        out += lines
out.append("}")
dst = Path(__file__).resolve().parent.parent / "App" / "Sources" / "Theme" / "Palettes.swift"
dst.write_text("\n".join(out) + "\n", encoding="utf-8")
print(len(blocks), "palettes ->", dst)
